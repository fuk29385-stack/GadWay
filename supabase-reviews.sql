create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  place_id text not null,
  user_id uuid references auth.users(id) on delete set null,
  author_name varchar(80) not null,
  rating smallint not null check (rating between 1 and 5),
  comment varchar(1000) not null check (length(btrim(comment)) > 0),
  created_at timestamptz not null default now()
);

create index if not exists reviews_place_created_idx
  on public.reviews (place_id, created_at desc);

alter table public.reviews enable row level security;
grant select, insert on public.reviews to anon, authenticated;
grant usage, select on sequence public.reviews_id_seq to anon, authenticated;

drop policy if exists "Anyone can read place reviews" on public.reviews;
create policy "Anyone can read place reviews"
  on public.reviews for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can add place reviews" on public.reviews;
create policy "Anyone can add place reviews"
  on public.reviews for insert
  to anon, authenticated
  with check (place_id <> '' and rating between 1 and 5 and length(btrim(author_name)) > 0 and length(btrim(comment)) > 0);
