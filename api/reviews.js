import { neon } from "@neondatabase/serverless";
import { applyCors } from "../lib/cors.js";

let sql;
function getSql() {
  if (!process.env.DATABASE_URL) {
    const error = new Error("DATABASE_URL is not configured");
    error.code = "DATABASE_URL_MISSING";
    throw error;
  }
  if (!sql) sql = neon(process.env.DATABASE_URL);
  return sql;
}

function ensureReviewsTable(db) {
  return db`CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id TEXT NOT NULL,
    user_id TEXT,
    author_name TEXT NOT NULL,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(1000) NOT NULL CHECK (length(btrim(comment)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
}

export default async function handler(request, response) {
  if (!applyCors(request, response, "GET, POST, OPTIONS")) {
    return response.status(403).json({ error: "Origin is not allowed" });
  }
  if (request.method === "OPTIONS") return response.status(204).end();
  if (request.method !== "GET" && request.method !== "POST") {
    response.setHeader("Allow", "GET, POST, OPTIONS");
    return response.status(405).json({ error: "Method not allowed" });
  }
  if (!process.env.DATABASE_URL) {
    return response.status(503).json({ error: "Reviews service is not configured" });
  }

  const db = getSql();
  try {
    await ensureReviewsTable(db);

    if (request.method === "GET") {
      const placeId = String(request.query.placeId || "").trim();
      if (!placeId || placeId.length > 200) {
        return response.status(400).json({ error: "A valid placeId is required" });
      }
      const [reviews, summaryRows] = await Promise.all([
        db`SELECT id, place_id, user_id, author_name, rating, comment, created_at
           FROM reviews WHERE place_id = ${placeId} ORDER BY created_at DESC, id DESC`,
        db`SELECT COUNT(*)::int AS count, COALESCE(ROUND(AVG(rating)::numeric, 1), 0)::float AS average
           FROM reviews WHERE place_id = ${placeId}`
      ]);
      return response.status(200).json({ reviews, summary: summaryRows[0] });
    }

    const body = request.body && typeof request.body === "object" ? request.body : {};
    const placeId = typeof body.placeId === "string" ? body.placeId.trim() : "";
    const rating = body.rating;
    const comment = typeof body.comment === "string" ? body.comment.trim() : "";
    // This project has no authentication. Keep guest reviews explicit and bounded.
    const authorName = typeof body.author_name === "string" ? body.author_name.trim().slice(0, 80) : "";
    if (!placeId || placeId.length > 200) return response.status(400).json({ error: "A valid placeId is required" });
    if (typeof rating !== "number" || !Number.isInteger(rating) || rating < 1 || rating > 5) {
      return response.status(400).json({ error: "Rating must be a number from 1 to 5" });
    }
    if (!comment) return response.status(400).json({ error: "Comment cannot be empty" });
    if (comment.length > 1000) return response.status(400).json({ error: "Comment must be at most 1000 characters" });
    if (!authorName) return response.status(400).json({ error: "Author name is required" });

    const [review] = await db`INSERT INTO reviews (place_id, user_id, author_name, rating, comment)
      VALUES (${placeId}, ${null}, ${authorName}, ${rating}, ${comment})
      RETURNING id, place_id, user_id, author_name, rating, comment, created_at`;
    return response.status(201).json({ review });
  } catch (error) {
    console.error("Reviews query failed", error);
    return response.status(500).json({ error: "Could not process reviews" });
  }
}
